package ex_02_Java_Basics_Part2;

public class Lab026_LocalVariables {
    public static void main(String[] args) {
        byte a = 127; // -128 to 127
        short b = 128; // 2 bytes
        char c = 'A'; // 2 bytes
        int d = 7; // 4 bytes
        long e = 93963634556L; // 8 bytes
        long e1 = 99632665666l;

        double f = 9933633.56666; // 8 bytes
        float g = 99333.266f; // 4 bytes
        float g1 = 9966.22343F;
    }
}
